package ode

import "math"

// Feagin12 is Feagin's 12th-order explicit Runge-Kutta integrator for
// first-order ODE systems. It uses 25 stages, advances with the 12th-order
// solution, and estimates the local error from Feagin's m-symmetry estimator
// — the scaled difference of two same-abscissa stages, adaptiveConst·(k2−k24).
//
// The coefficients are the Float64 values from SciML/OrdinaryDiffEq.jl's
// Feagin12ConstantCache (the CompiledFloats path). DiffEq.jl carries a final
// FSAL evaluation f(u, t+dt); it feeds only the next step's first stage and
// neither the solution nor the error estimate, so this non-FSAL implementation
// omits it and simply re-evaluates stage 0 each step.
type Feagin12 struct {
	// Step control — set before calling Init or Step.
	hMin, hMax float64
	atol, rtol float64

	// Diagnostics.
	LastErrNorm float64
	StepCount   int

	t  float64
	y  []float64
	fn func(dst, y []float64, t float64)

	// Workspace (allocated once by Init).
	k      [25][]float64
	tmp    []float64
	yNew   []float64
	errBuf []float64
}

// Configure validates and applies step-control parameters. Call before Init.
func (rk *Feagin12) Configure(cfg Parameters) error {
	if err := cfg.Validate(); err != nil {
		return err
	}
	rk.atol = cfg.AbsTolerance
	rk.rtol = cfg.RelTolerance
	rk.hMax = cfg.MaxStep
	rk.hMin = cfg.MinStep
	return nil
}

// Init binds the initial value problem and allocates workspace.
func (rk *Feagin12) Init(ivp IVP1) {
	n := len(ivp.Y0)
	rk.t = ivp.T0
	rk.y = append(make([]float64, 0, n), ivp.Y0...)
	rk.fn = ivp.Func
	for i := range rk.k {
		rk.k[i] = make([]float64, n)
	}
	rk.tmp = make([]float64, n)
	rk.yNew = make([]float64, n)
	rk.errBuf = make([]float64, n)
	rk.LastErrNorm = 0
	rk.StepCount = 0
}

// State returns the current time and a view of the current state vector.
func (rk *Feagin12) State() (t float64, y []float64) {
	return rk.t, rk.y
}

// SetState overwrites the current integration state.
func (rk *Feagin12) SetState(t float64, y []float64) {
	rk.t = t
	copy(rk.y, y)
}

// SelectInitialStep computes a safe first step size following Hairer, Norsett &
// Wanner §II.4, the same algorithm used by scipy's select_initial_step.
func (rk *Feagin12) SelectInitialStep() float64 {
	return selectInitialStep(rk.fn, rk.t, rk.y, rk.atol, rk.rtol, 11.0)
}

// Step performs a single Feagin12 step. Returns the suggested step size for the next call.
// In non-adaptive mode (atol=rtol=0) the step is always accepted and h is returned unchanged.
func (rk *Feagin12) Step(h float64) float64 {
	const (
		safety = 0.9
		minFac = 0.2
		maxFac = 10.0
		order  = 12.0
	)
	adaptive := rk.atol > 0 || rk.rtol > 0
	t := rk.t
	y := rk.y
	n := len(y)
	fn := rk.fn

	stepRejected := false
	for {
		tNext := t + h
		hEff := tNext - t

		// Stage 0.
		fn(rk.k[0], y, t)

		// Stages 1..24.
		for i := 1; i < 25; i++ {
			for c := range n {
				sum := 0.0
				for j := range i {
					sum += feaginA[i][j] * rk.k[j][c]
				}
				rk.tmp[c] = y[c] + hEff*sum
			}
			fn(rk.k[i], rk.tmp, t+feaginC[i]*hEff)
		}

		// 12th-order solution and Feagin's embedded error estimate.
		for c := range n {
			sumB, sumE := 0.0, 0.0
			for i := range 25 {
				sumB += feaginB[i] * rk.k[i][c]
				sumE += feaginE[i] * rk.k[i][c]
			}
			rk.yNew[c] = y[c] + hEff*sumB
			rk.errBuf[c] = hEff * sumE
		}

		if !adaptive {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			rk.StepCount++
			return hEff
		}

		// Squared RMS error norm with per-component scaling — matches scipy's
		// rms_norm. We keep it squared and fold the missing sqrt into the Pow
		// exponent below, since errNorm^(-1/order) == errNorm2^(-0.5/order).
		sumSq := 0.0
		for c := range n {
			sc := rk.atol + rk.rtol*math.Max(math.Abs(y[c]), math.Abs(rk.yNew[c]))
			e := rk.errBuf[c] / sc
			sumSq += e * e
		}
		errNorm2 := sumSq / float64(n)

		if errNorm2 <= 1 {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			rk.LastErrNorm = math.Sqrt(errNorm2)
			rk.StepCount++
			if errNorm2 == 0 {
				return math.Min(hEff*maxFac, rk.hMax)
			}
			factorClamped := math.Max(minFac, math.Min(maxFac, safety*math.Pow(errNorm2, -0.5/order)))
			if stepRejected {
				factorClamped = math.Min(1.0, factorClamped)
			}
			return math.Max(rk.hMin, math.Min(rk.hMax, hEff*factorClamped))
		}

		factor := math.Max(minFac, safety*math.Pow(errNorm2, -0.5/order))
		h = math.Max(rk.hMin, hEff*factor)
		stepRejected = true

		if h <= rk.hMin {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			return rk.hMin
		}
	}
}

