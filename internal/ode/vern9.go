package ode

import "math"

// Verner9 is Verner's "most efficient" order-9 Runge-Kutta integrator for
// first-order ODE systems. It uses 16 stages, advances with the 9th-order
// solution, and estimates the local error from the embedded 8th-order pair.
//
// The coefficients are Verner's exact rational/√6 values, transcribed from
// SciML/OrdinaryDiffEq.jl's Vern9Tableau. This implementation reproduces the
// integrating step only; it omits the optional "lazy" 9th-order dense
// interpolant (an extra 10 stages) that DiffEq.jl computes for continuous
// output.
type Verner9 struct {
	// Step control — set before calling Init or Step.
	hMin, hMax float64
	atol, rtol float64

	// Diagnostics.
	LastErrNorm float64
	StepCount   int

	t  float64
	y  []float64
	fn func(dst, y []float64, t float64)

	// Workspace (allocated once by Init).
	k      [16][]float64
	tmp    []float64
	yNew   []float64
	errBuf []float64
}

// Configure validates and applies step-control parameters. Call before Init.
func (rk *Verner9) Configure(cfg Parameters) error {
	if err := cfg.Validate(); err != nil {
		return err
	}
	rk.atol = cfg.AbsTolerance
	rk.rtol = cfg.RelTolerance
	rk.hMax = cfg.MaxStep
	rk.hMin = cfg.MinStep
	return nil
}

// Init binds the initial value problem and allocates workspace.
func (rk *Verner9) Init(ivp IVP1) {
	n := len(ivp.Y0)
	rk.t = ivp.T0
	rk.y = append(make([]float64, 0, n), ivp.Y0...)
	rk.fn = ivp.Func
	for i := range rk.k {
		rk.k[i] = make([]float64, n)
	}
	rk.tmp = make([]float64, n)
	rk.yNew = make([]float64, n)
	rk.errBuf = make([]float64, n)
	rk.LastErrNorm = 0
	rk.StepCount = 0
}

// State returns the current time and a view of the current state vector.
func (rk *Verner9) State() (t float64, y []float64) {
	return rk.t, rk.y
}

// SetState overwrites the current integration state.
func (rk *Verner9) SetState(t float64, y []float64) {
	rk.t = t
	copy(rk.y, y)
}

// SelectInitialStep computes a safe first step size following Hairer, Norsett &
// Wanner §II.4, the same algorithm used by scipy's select_initial_step.
func (rk *Verner9) SelectInitialStep() float64 {
	const errOrder = 8.0
	n := len(rk.y)
	nf := float64(n)
	fn := rk.fn
	y := rk.y
	t := rk.t
	atol, rtol := rk.atol, rk.rtol

	f0 := make([]float64, n)
	fn(f0, y, t)

	d0, d1 := 0.0, 0.0
	for i, yi := range y {
		sc := atol + math.Abs(yi)*rtol
		d0 += (yi / sc) * (yi / sc)
		d1 += (f0[i] / sc) * (f0[i] / sc)
	}
	d0 = math.Sqrt(d0 / nf)
	d1 = math.Sqrt(d1 / nf)

	var h0 float64
	if d0 < 1e-5 || d1 < 1e-5 {
		h0 = 1e-6
	} else {
		h0 = 0.01 * d0 / d1
	}

	// Euler probe step to estimate second derivative.
	y1 := make([]float64, n)
	for i, yi := range y {
		y1[i] = yi + h0*f0[i]
	}
	f1 := make([]float64, n)
	fn(f1, y1, t+h0)

	d2 := 0.0
	for i := range f1 {
		sc := atol + math.Abs(y[i])*rtol
		dd := (f1[i] - f0[i]) / sc
		d2 += dd * dd
	}
	d2 = math.Sqrt(d2/nf) / h0

	var h1 float64
	if maxD := math.Max(d1, d2); maxD <= 1e-5 {
		h1 = math.Max(1e-6, h0*1e-3)
	} else {
		h1 = math.Pow(0.01/maxD, 1.0/(errOrder+1))
	}
	return math.Min(100*h0, h1)
}

// Step performs a single Vern9 step. Returns the suggested step size for the next call.
// In non-adaptive mode (atol=rtol=0) the step is always accepted and h is returned unchanged.
func (rk *Verner9) Step(h float64) float64 {
	const (
		safety = 0.9
		minFac = 0.2
		maxFac = 10.0
		order  = 9.0
	)
	adaptive := rk.atol > 0 || rk.rtol > 0
	t := rk.t
	y := rk.y
	n := len(y)
	fn := rk.fn

	stepRejected := false
	for {
		tNext := t + h
		hEff := tNext - t

		// Stage 0.
		fn(rk.k[0], y, t)

		// Stages 1..15.
		for i := 1; i < 16; i++ {
			for c := range n {
				sum := 0.0
				for j := range i {
					sum += vern9A[i][j] * rk.k[j][c]
				}
				rk.tmp[c] = y[c] + hEff*sum
			}
			fn(rk.k[i], rk.tmp, t+vern9C[i]*hEff)
		}

		// 9th-order solution and embedded 8th-order error estimate.
		for c := range n {
			sumB, sumE := 0.0, 0.0
			for i := range 16 {
				sumB += vern9B[i] * rk.k[i][c]
				sumE += vern9E[i] * rk.k[i][c]
			}
			rk.yNew[c] = y[c] + hEff*sumB
			rk.errBuf[c] = hEff * sumE
		}

		if !adaptive {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			rk.StepCount++
			return hEff
		}

		// Squared RMS error norm with per-component scaling — matches scipy's
		// rms_norm. We keep it squared and fold the missing sqrt into the Pow
		// exponent below, since errNorm^(-1/order) == errNorm2^(-0.5/order).
		sumSq := 0.0
		for c := range n {
			sc := rk.atol + rk.rtol*math.Max(math.Abs(y[c]), math.Abs(rk.yNew[c]))
			e := rk.errBuf[c] / sc
			sumSq += e * e
		}
		errNorm2 := sumSq / float64(n)

		if errNorm2 <= 1 {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			rk.LastErrNorm = math.Sqrt(errNorm2)
			rk.StepCount++
			if errNorm2 == 0 {
				return math.Min(hEff*maxFac, rk.hMax)
			}
			factorClamped := math.Max(minFac, math.Min(maxFac, safety*math.Pow(errNorm2, -0.5/order)))
			if stepRejected {
				factorClamped = math.Min(1.0, factorClamped)
			}
			return math.Max(rk.hMin, math.Min(rk.hMax, hEff*factorClamped))
		}

		factor := math.Max(minFac, safety*math.Pow(errNorm2, -0.5/order))
		h = math.Max(rk.hMin, hEff*factor)
		stepRejected = true

		if h <= rk.hMin {
			rk.t = tNext
			copy(rk.y, rk.yNew)
			return rk.hMin
		}
	}
}

