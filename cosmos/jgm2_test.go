// TestJGM2TableMatchesGMATCopy cross-checks the generated jgm2.go table
// against jgmrecoef (hand-copied from GMAT's JGM2.cof in jgm2_test.go):
// every coefficient must agree exactly, every jgm2.go entry must be accounted
// for, and a Harmonics built from each source must produce identical
// accelerations.
func TestJGM2TableMatchesGMATCopy(t *testing.T) {
	// Exact value agreement, entry by entry.
	seen := make(map[int]bool, len(jgmrecoef))
	for _, e := range jgmrecoef {
		if e.i < 2 || e.i > jgm2Degree || e.j < 0 || e.j > e.i {
			t.Fatalf("bad reference entry n=%d m=%d", e.i, e.j)
		}
		k := triIndex(e.i, e.j)
		if seen[k] {
			t.Fatalf("duplicate reference entry n=%d m=%d", e.i, e.j)
		}
		seen[k] = true
		if jgm2C[k] != e.x || jgm2S[k] != e.y {
			t.Errorf("coefficient n=%d m=%d: jgm2.go C=%v S=%v, GMAT copy C=%v S=%v",
				e.i, e.j, jgm2C[k], jgm2S[k], e.x, e.y)
		}
	}
	// Completeness both ways: the reference holds the full n=2..21 triangle...
	if want := (jgm2Degree+1)*(jgm2Degree+2)/2 - 3; len(jgmrecoef) != want {
		t.Errorf("reference table has %d entries, want %d (full n=2..%d triangle)", len(jgmrecoef), want, jgm2Degree)
	}
	// ...and jgm2.go has no nonzero coefficient the reference doesn't cover
	// (n=0 central term aside; degree 1 must be zero: origin at center of mass).
	for n := 0; n <= jgm2Degree; n++ {
		for m := 0; m <= n; m++ {
			k := triIndex(n, m)
			if seen[k] {
				continue
			}
			switch {
			case n == 0:
				if jgm2C[k] != 1 || jgm2S[k] != 0 {
					t.Errorf("central term: C=%v S=%v, want 1, 0", jgm2C[k], jgm2S[k])
				}
			default: // n == 1 rows only
				if jgm2C[k] != 0 || jgm2S[k] != 0 {
					t.Errorf("uncovered nonzero coefficient n=%d m=%d: C=%v S=%v", n, m, jgm2C[k], jgm2S[k])
				}
			}
		}
	}

	// Behavioral agreement: identical accelerations from both sources.
	nCoef := triIndex(jgm2Degree, jgm2Degree) + 1
	c := make([]float64, nCoef)
	s := make([]float64, nCoef)
	c[triIndex(0, 0)] = 1
	for _, e := range jgmrecoef {
		k := triIndex(e.i, e.j)
		c[k], s[k] = e.x, e.y
	}
	ref, err := NewHarmonics("JGM-2 GMAT copy", jgm2Mu, jgm2Radius, jgm2Degree, jgm2Degree, c, s)
	if err != nil {
		t.Fatal(err)
	}
	gen, err := JGM2(jgm2Degree, jgm2Degree)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range []md3.Vec{
		{X: 6928.5e3},
		{X: 4000e3, Y: 3000e3, Z: 4500e3},
		{X: -1500e3, Y: -2500e3, Z: 6500e3},
		{Y: -6378.1363e3, Z: 1e3},
		{X: 2000e3, Y: -6300e3, Z: -2500e3},
	} {
		ga, ra := gen.AccelBodyFixed(p), ref.AccelBodyFixed(p)
		if ga != ra {
			t.Errorf("acceleration mismatch at %v:\n  jgm2.go   %.18g\n  GMAT copy %.18g\n  |Δ| %g m/s²",
				p, ga, ra, md3.Norm(md3.Sub(ga, ra)))
		}
	}
}

